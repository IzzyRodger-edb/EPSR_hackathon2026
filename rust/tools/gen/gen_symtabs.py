#!/usr/bin/env python3
"""Generate epsr-core/src/symtab_tools.rs from fortran_src/setup_symbols_generic.f.

Each `subroutine setup_symbols_<tool>()` is a hard-coded keyword table.  This
script joins Fortran continuation lines, evaluates the string constants
(including `//` concatenations) and emits one `ToolTable` per routine.
Statements that are not part of the standard table pattern are copied into
the `notes` field so that the Rust tool code can reproduce them.
"""
import re, sys, os
here = os.path.dirname(os.path.abspath(__file__))
src_path = os.path.join(here, '../../../fortran_src/setup_symbols_generic.f')
out_path = os.path.join(here, '../../epsr-core/src/symtab_tools.rs')
raw = open(src_path, errors='replace').read().split('\n')
# join continuation lines (fixed form: column 6 non-blank)
stmts = []
for l in raw:
    if l[:1] in 'cC*!' or l.strip().startswith('!'):
        continue
    if len(l) > 5 and l[5] not in ' 0' and l[:5].strip() == '' and stmts:
        stmts[-1] += l[6:].strip()
    else:
        stmts.append(l)
def strval(expr):
    parts = re.findall(r"'((?:[^']|'')*)'", expr)
    if not parts:
        return None
    rest = re.sub(r"'((?:[^']|'')*)'", '', expr).replace('//', '').strip()
    if rest:
        return None
    return ''.join(p.replace("''", "'") for p in parts)
std = re.compile(r"^(include .*|iref=0|nsymbolplus=nsymboldata-nsymboluptodata|nsymbol=iref|do is=1,nsymbol|symbol_value\(is\)=symbol_default\(is\)|write\(6,100\).*|100\s+format.*|end do|read\(symbol_value\(nsymboluptodata\),\*,iostat=ierr\) nfiles|if\(nsymboluptodata.ge.nsymboldata.or.ierr.ne.0\) nfiles=1|ilenprompt=index\(prompt,'>'\)|ilendataprompt=index\(dataprompt,' '\)-1|ilenextinp=index\(extinp,' '\)-1|return)$")
tables = []
i = 0
while i < len(stmts):
    m = re.match(r"\s+subroutine setup_symbols_(\w+)\(\)", stmts[i])
    i += 1
    if not m:
        continue
    name = m.group(1)
    ent, marks, attrs, notes = [], [], {}, []
    cur = None
    while i < len(stmts) and not re.match(r"\s+end\s*$", stmts[i]):
        s = stmts[i].strip(); i += 1
        if not s:
            continue
        s = re.sub(r"\s*!.*$", "", s) if "'" not in s else s
        if s == "iref=iref+1":
            cur = {'symbol_default': None}; ent.append(cur); continue
        mm = re.match(r"(symbol|symbol_type|symbol_text|symbol_default)\(iref\)\s*=\s*(.*)$", s)
        if mm:
            v = strval(mm.group(2))
            if v is None:
                notes.append(s); cur[mm.group(1)] = cur.get(mm.group(1)) or ''
            else:
                cur[mm.group(1)] = v
            continue
        mm = re.match(r"iflag\(iref\)\s*=\s*(-?\d+)", s)
        if mm:
            cur['iflag'] = int(mm.group(1)); continue
        mm = re.match(r"(\w+)\s*=\s*iref(\+1)?\s*$", s)
        if mm:
            marks.append((mm.group(1), len(ent) + (1 if mm.group(2) else 0))); continue
        mm = re.match(r"(prompt|dataprompt|dataprompttext|extinp)\s*=\s*(.*)$", s)
        if mm and strval(mm.group(2)) is not None:
            attrs[mm.group(1)] = strval(mm.group(2)); continue
        if std.match(s):
            continue
        if re.match(r"write\(symbol_(text|default)\(iref\)", s) or re.match(r"\d+\s+format", s):
            notes.append(s); continue
        notes.append(s)
    tables.append((name, ent, marks, attrs, notes))
def q(s):
    return '"' + (s or '').replace('\\', '\\\\').replace('"', '\\"') + '"'
o = []
o.append("//! Keyword tables of the EPSR auxiliary programs — GENERATED by\n//! `tools/gen/gen_symtabs.py` from `fortran_src/setup_symbols_generic.f`.\n//! Do not edit by hand.\n//!\n//! `notes` lists Fortran statements of the routine that are not plain table\n//! entries (computed defaults, special `nfiles` rules, ...); the tool module\n//! using the table must reproduce them (see `symbols::State::install_tool_table`).\n")
o.append("use crate::symbols::ToolTable;\n")
for name, ent, marks, attrs, notes in tables:
    o.append(f"/// `setup_symbols_{name}`")
    o.append(f"pub static {name.upper()}: ToolTable = ToolTable {{")
    o.append(f"    name: {q(name)},")
    o.append(f"    extinp: {q(attrs.get('extinp'))},")
    o.append(f"    prompt: {q(attrs.get('prompt'))},")
    o.append(f"    dataprompt: {q(attrs.get('dataprompt'))},")
    o.append(f"    dataprompttext: {q(attrs.get('dataprompttext'))},")
    o.append("    symbols: &[")
    for e in ent:
        o.append(f"        ({q(e.get('symbol'))}, '{(e.get('symbol_type') or ' ')[:1]}', {e.get('iflag',0)}, {q(e.get('symbol_default'))}, {q(e.get('symbol_text'))}),")
    o.append("    ],")
    o.append("    marks: &[" + ", ".join(f"({q(a)}, {b})" for a, b in marks) + "],")
    o.append("    notes: &[" + ", ".join(q(n) for n in notes if not n.startswith('include')) + "],")
    o.append("};\n")
o.append("/// All tables, by tool name.")
o.append("pub static ALL: &[&ToolTable] = &[" + ", ".join(f"&{t[0].upper()}" for t in tables) + "];")
open(out_path, 'w').write('\n'.join(o) + '\n')
print(f"wrote {len(tables)} tables to {out_path}")
for name, ent, marks, attrs, notes in tables:
    nn = [n for n in notes if not n.startswith('include')]
    if nn: print(name, nn)
