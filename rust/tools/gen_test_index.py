#!/usr/bin/env python3
"""Write docs/TEST_CASES.md: one row per test_problems/<system>/EPSR-test-ex* folder (title from its
README.md, programs from commands.txt, number of chained passes).

usage: gen_test_index.py [REPO_ROOT]   (default: two levels above this script)"""

import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = (
    sys.argv[1]
    if len(sys.argv) > 1
    else os.path.normpath(os.path.join(here, "..", ".."))
)
rows = []
tp = os.path.join(root, "test_problems")
cases = [
    (system, name)
    for system in sorted(os.listdir(tp))
    if os.path.isdir(os.path.join(tp, system))
    for name in os.listdir(os.path.join(tp, system))
]
for system, name in cases:
    m = re.fullmatch(r"EPSR-test-ex(\d+)", name)
    if not m:
        continue
    d = os.path.join(tp, system, name)
    title = ""
    rd = os.path.join(d, "README.md")
    if os.path.exists(rd):
        first = open(rd, encoding="utf-8").readline().strip().lstrip("#").strip()
        title = re.sub(r"^EPSR-test-ex\d+\s*[—-]\s*", "", first)
    progs, rep = [], 1
    cf = os.path.join(d, "commands.txt")
    if os.path.exists(cf):
        for line in open(cf):
            line = line.split("#")[0].strip()
            if not line:
                continue
            w = line.split()
            if w[0] == "repeat":
                rep = int(w[1])
            elif w[0] not in progs:
                progs.append(w[0])
    ref = (
        "yes"
        if os.path.exists(os.path.join(d, "fortran_reference.tar.gz"))
        else "**no**"
    )
    rows.append(
        (int(m.group(1)), system, title.replace("|", "\\|"), ", ".join(progs), rep, ref)
    )
rows.sort()
out = [
    "# Verification test cases (`EPSR-test-ex*`)",
    "",
    "Generated by `rust/tools/gen_test_index.py` from the `README.md` and `commands.txt` of every",
    "`test_problems/<system>/EPSR-test-ex{N}` folder (all current cases are in `test_problems/200DMSO400Water`). Each folder holds the inputs, `commands.txt` (one",
    "program call per line, `repeat N` = run the list N times, chaining the outputs), a `README.md` describing",
    "what is exercised, a one-page summary `EPSR-test-exN.pdf`, and `fortran_reference.tar.gz` with the files written by the Fortran",
    "(gfortran -O2 -fno-tree-vectorize). Run one case with `rust/tools/run_ex_test.sh test_problems/200DMSO400Water/EPSR-test-exN <fortran build>`",
    "or all of them with `rust/tools/run_all_ex_tests.sh <fortran build>` (see VALIDATION.md).",
    "",
    f"{len(rows)} cases.",
    "",
    "| case | programs | passes | what is tested | reference |",
    "|---|---|---|---|---|",
]
for n, system, t, p, r, ref in rows:
    out.append(
        f"| [ex{n}](../../test_problems/{system}/EPSR-test-ex{n}/README.md) | {p} | {r} | {t} | {ref} |"
    )
open(os.path.join(here, "..", "docs", "TEST_CASES.md"), "w").write(
    "\n".join(out) + "\n"
)
print(f"wrote docs/TEST_CASES.md ({len(rows)} cases)")
