#!/usr/bin/env python3
"""Record hashes of the Fortran reference outputs for the Rust regression test.

usage: make_reference_hashes.py PRISTINE_DIR REFERENCE_DIR OUTPUT_FILE

PRISTINE_DIR   the test inputs before the run (e.g. ../EPSR-test)
REFERENCE_DIR  the same folder after one run of the Fortran `epsr`
OUTPUT_FILE    e.g. epsr-core/tests/reference_hashes.txt

Every file that the run created or changed is hashed (64-bit FNV-1a) after
masking the run-dependent parts (date line of `.out`, timing columns of
`fort.35`).  `epsr-core/tests/test_case.rs` applies the same masking to the
Rust outputs and compares the hashes.
"""

import os
import sys


def mask(name, data):
    lines = data.decode("latin-1").split("\n")
    if name.endswith(".out") and len(lines) > 1:
        lines[1] = "<date>"
    if name == "fort.35":
        lines = [l if l.startswith("#") else " ".join(l.split()[:3]) for l in lines]
    return "\n".join(lines).encode("latin-1")


def fnv1a64(b):
    h = 0xCBF29CE484222325
    for c in b:
        h ^= c
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    pristine, ref, out = sys.argv[1:4]
    rows = []
    for name in sorted(os.listdir(ref)):
        p = os.path.join(ref, name)
        if not os.path.isfile(p) or name == "run.log":
            continue
        with open(p, "rb") as f:
            data = f.read()
        q = os.path.join(pristine, name)
        if os.path.exists(q):
            with open(q, "rb") as f:
                if f.read() == data:
                    continue
        rows.append(f"{fnv1a64(mask(name, data)):016x} {name}")
    with open(out, "w") as f:
        f.write(
            "# FNV-1a 64 hashes of the masked outputs of one Fortran `epsr` run on ../EPSR-test\n"
        )
        f.write(
            "# (gfortran -O2 -fno-tree-vectorize; generated by tools/make_reference_hashes.py)\n"
        )
        f.write("\n".join(rows) + "\n")
    print(f"wrote {len(rows)} hashes to {out}")


if __name__ == "__main__":
    main()
